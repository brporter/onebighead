import { act, render, screen, within } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import { afterEach, expect, it, vi } from 'vitest';
import DataContext from './testUtils/DataContext';
import CollectionSetupWizard from '../src/components/collection/CollectionSetupWizard';
import { createMockCollection, createMockCollectionTheme, createMockDataContextValue } from './testUtils/factories';
import { deferred } from './testUtils/deferred';

afterEach(() => vi.restoreAllMocks());
const general = createMockCollectionTheme({ themeId: 1, name: 'General', templates: [], categories: [] });
const books = createMockCollectionTheme({ themeId: 2, name: 'Books', templates: [], categories: [] });

it('keeps the inline draft through every step, locks pending controls, and retries a failed creation', async () => {
  const user = userEvent.setup();
  const pending = deferred<ReturnType<typeof createMockCollection>>();
  const context = createMockDataContextValue({ themes: [general, books], setupCollection: vi.fn().mockReturnValueOnce(pending.promise).mockResolvedValue(createMockCollection({ collectionId: 9 })) });
  const done = vi.fn();
  const status = vi.fn();
  render(<DataContext value={context}><CollectionSetupWizard isModal onComplete={done} onCancel={vi.fn()} onStatusChange={status} /></DataContext>);
  expect(screen.getByRole('heading', { level: 2, name: 'New Collection' })).toBeInTheDocument();
  expect(screen.queryByRole('button', { name: 'Skip Setup' })).not.toBeInTheDocument();
  expect(screen.getByRole('button', { name: 'Next' })).toBeDisabled();
  await user.type(screen.getByRole('textbox', { name: 'Collection Name' }), ' Library ');
  await user.type(screen.getByRole('textbox', { name: 'Description' }), ' First editions ');
  await user.click(screen.getByRole('button', { name: 'Next' }));
  await user.click(screen.getByRole('button', { name: /Books/ }));
  await user.click(screen.getByRole('button', { name: 'Next' }));
  expect(screen.getByRole('button', { name: 'Preview' })).toHaveAttribute('aria-current', 'step');
  expect(screen.getByText('First editions')).toBeInTheDocument();
  await user.click(screen.getByRole('button', { name: 'Previous' }));
  await user.click(screen.getByRole('button', { name: 'Previous' }));
  expect(screen.getByRole('textbox', { name: 'Collection Name' })).toHaveValue(' Library ');
  await user.click(screen.getByRole('button', { name: 'Preview' }));
  await user.click(screen.getByRole('button', { name: 'Create Collection' }));
  expect(status).toHaveBeenLastCalledWith({ dirty: true, pending: true });
  for (const button of screen.getAllByRole('button')) expect(button).toBeDisabled();
  await act(async () => pending.reject(new Error('Connection lost')));
  expect(screen.getByRole('alert')).toHaveTextContent('Connection lost');
  expect(done).not.toHaveBeenCalled();
  await user.click(screen.getByRole('button', { name: 'Create Collection' }));
  expect(context.setupCollection).toHaveBeenLastCalledWith({ name: 'Library', description: 'First editions', themeId: 2 });
  expect(done).toHaveBeenCalledExactlyOnceWith(9);
});

it('supports full-page default setup and warns before discarding an edited draft', async () => {
  const user = userEvent.setup();
  const confirm = vi.spyOn(window, 'confirm').mockReturnValue(false);
  const context = createMockDataContextValue({ themes: [general], setupCollection: vi.fn().mockResolvedValue(createMockCollection({ collectionId: 3 })) });
  const done = vi.fn();
  const cancel = vi.fn();
  render(<DataContext value={context}><CollectionSetupWizard onComplete={done} onCancel={cancel} /></DataContext>);
  expect(screen.getByRole('heading', { level: 1 })).toHaveTextContent('Create Your Collection');
  await user.click(screen.getByRole('button', { name: 'Cancel' }));
  expect(cancel).toHaveBeenCalledOnce();
  expect(confirm).not.toHaveBeenCalled();
  await user.type(screen.getByRole('textbox', { name: 'Description' }), 'Notes');
  await user.click(screen.getByRole('button', { name: 'Cancel' }));
  expect(cancel).toHaveBeenCalledOnce();
  confirm.mockReturnValue(true);
  await user.click(screen.getByRole('button', { name: 'Cancel' }));
  expect(cancel).toHaveBeenCalledTimes(2);
  await user.click(screen.getByRole('button', { name: 'Skip Setup' }));
  expect(context.setupCollection).toHaveBeenCalledExactlyOnceWith({ name: 'My Collection', description: 'Notes', themeId: 1 });
  expect(done).toHaveBeenCalledWith(3);
});

it('shows loading, retry and empty states for themes without losing the name', async () => {
  const user = userEvent.setup();
  const context = createMockDataContextValue({ themes: [], themesLoading: true });
  const view = (state: typeof context) => <DataContext value={state}><CollectionSetupWizard onComplete={vi.fn()} /></DataContext>;
  const { rerender } = render(view(context));
  await user.type(screen.getByRole('textbox', { name: 'Collection Name' }), 'Library');
  await user.click(screen.getByRole('button', { name: 'Theme' }));
  expect(screen.getByRole('status')).toHaveTextContent('Loading themes...');
  rerender(view({ ...context, themesLoading: false, themesError: 'Offline' }));
  await user.click(screen.getByRole('button', { name: 'Try again' }));
  expect(context.loadThemes).toHaveBeenCalledTimes(2);
  rerender(view({ ...context, themesLoading: false }));
  expect(screen.getByRole('status')).toHaveTextContent('No themes available');
  await user.click(screen.getByRole('button', { name: 'Try again' }));
  expect(context.loadThemes).toHaveBeenCalledTimes(3);
  rerender(view({ ...context, themesLoading: false, themes: [books] }));
  expect(screen.getByRole('button', { name: 'Preview' })).toBeDisabled();
  await user.click(screen.getByRole('button', { name: /Books/ }));
  await user.click(screen.getByRole('button', { name: 'Preview' }));
  const summary = screen.getByRole('heading', { name: 'Collection Summary' }).parentElement!;
  expect(within(summary).getByText('Library')).toBeInTheDocument();
  expect(within(summary).queryByText('Description')).not.toBeInTheDocument();
  rerender(view({ ...context, themesLoading: false }));
  expect(screen.getByRole('status')).toHaveTextContent('Choose an available theme');
  expect(screen.getByRole('button', { name: 'Create Collection' })).toBeDisabled();
});
