using System.Data;
using System.Text.Json;
using Microsoft.EntityFrameworkCore;
using OneBigHead.Server.Data;
using OneBigHead.Server.Models;

namespace OneBigHead.Server.Services.Images;

/// <summary>Authorizes image bytes from a consistent snapshot of membership and publication state.</summary>
public sealed class ImageReader(IDbContextFactory<AppDbContext> contexts, IVisibilityService visibility) : IImageReader
{
    public async Task<RetrievedImage?> ReadAsync(Guid key, int? userId, int? workspaceId, CancellationToken cancellationToken)
    {
        await using var context = await contexts.CreateDbContextAsync(cancellationToken);
        await using var snapshot = await context.Database.BeginTransactionAsync(IsolationLevel.RepeatableRead, cancellationToken);
        var image = await context.StoredImages.AsNoTracking()
            .Where(image => image.Id == key && !image.Workspace!.IsDeleted)
            .Select(image => new { image.WorkspaceId, image.Workspace!.Slug })
            .SingleOrDefaultAsync(cancellationToken);
        if (image is null) return null;

        var member = userId is > 0 && workspaceId == image.WorkspaceId &&
            await context.WorkspaceUsers.AnyAsync(membership => membership.UserId == userId &&
                membership.WorkspaceId == image.WorkspaceId && !membership.User!.IsDeleted, cancellationToken);
        if (!member && (string.IsNullOrWhiteSpace(image.Slug) ||
            !await HasPublicReferenceAsync(context, key, image.WorkspaceId, cancellationToken))) return null;

        return await context.StoredImages.AsNoTracking().Where(stored => stored.Id == key)
            .Select(stored => new RetrievedImage(stored.Data, stored.ContentType, stored.FileName))
            .SingleAsync(cancellationToken);
    }

    private async Task<bool> HasPublicReferenceAsync(AppDbContext context, Guid key, int workspaceId, CancellationToken cancellationToken)
    {
        // References generated by image uploads are application-relative. An external URL
        // with the same path must never grant access to this application's stored bytes.
        var url = $"/api/images/{key}";
        if (await context.Collections.AnyAsync(collection => collection.WorkspaceId == workspaceId &&
            collection.Visibility == Visibility.Public && collection.HeroImageUrl == url, cancellationToken)) return true;

        // Images are persisted as JSON in a text column. Cast in PostgreSQL so
        // unrelated image lists/properties are not materialized; the value is parameterized.
        var reference = JsonSerializer.Serialize(new[] { new { url } });
        var references = await context.Items.FromSqlInterpolated($"""
            SELECT * FROM "Items" WHERE "Images"::jsonb @> {reference}::jsonb
            """).AsNoTracking()
            .Where(item => item.WorkspaceId == workspaceId && item.Visibility == Visibility.Public &&
                item.Collection!.WorkspaceId == workspaceId && item.Collection.Visibility == Visibility.Public)
            .Select(item => new
            {
                Item = new Item { Id = item.Id, WorkspaceId = item.WorkspaceId, CollectionId = item.CollectionId,
                    CategoryId = item.CategoryId, Visibility = item.Visibility },
                Collection = item.Collection!
            }).ToListAsync(cancellationToken);
        var collectionIds = references.Select(row => row.Collection.Id).Distinct().ToList();
        var categories = await context.Categories.AsNoTracking()
            .Where(category => category.WorkspaceId == workspaceId && collectionIds.Contains(category.CollectionId))
            .ToListAsync(cancellationToken);
        foreach (var group in references.GroupBy(row => row.Collection.Id))
        {
            var collection = group.First().Collection;
            var collectionCategories = categories.Where(category => category.CollectionId == collection.Id).ToList();
            var items = group.Select(row => row.Item).ToList();
            visibility.ComputeEffectiveVisibility(collectionCategories, collection);
            visibility.ComputeEffectiveVisibility(items, collection, collectionCategories);
            if (items.Any(item => item.EffectiveIsPublic)) return true;
        }
        return false;
    }
}
