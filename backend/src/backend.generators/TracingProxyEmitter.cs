using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis.CSharp;

namespace OneBigHead.Generators;

/// <summary>Emits one forwarding pattern for synchronous and asynchronous return shapes.</summary>
internal static class TracingProxyEmitter
{
    public static string Emit(TracingContract contract)
    {
        var source = new StringBuilder();
        source.AppendLine("// <auto-generated />");
        source.AppendLine("#nullable enable");
        source.AppendLine("using System.Diagnostics;");
        if (contract.Namespace.Length > 0) source.AppendLine($"namespace {contract.Namespace};");
        source.AppendLine($"public class TracingProxy_{contract.Name} : {Escape(contract.Name)}");
        source.AppendLine("{");
        source.AppendLine($"    private readonly {Escape(contract.Name)} _inner;");
        source.AppendLine("    private readonly ActivitySource _activitySource;");
        source.AppendLine($"    public TracingProxy_{contract.Name}({Escape(contract.Name)} inner, ActivitySource activitySource)");
        source.AppendLine("    {");
        source.AppendLine("        _inner = inner;");
        source.AppendLine("        _activitySource = activitySource;");
        source.AppendLine("    }");
        foreach (var method in contract.Methods) EmitMethod(source, contract, method);
        source.AppendLine("}");
        return source.ToString();
    }

    private static void EmitMethod(StringBuilder source, TracingContract contract, TracingMethod method)
    {
        var asynchronous = method.ReturnKind is TracingReturnKind.Task or TracingReturnKind.TaskOfT or TracingReturnKind.ValueTask or TracingReturnKind.ValueTaskOfT;
        var returnsValue = method.ReturnKind is TracingReturnKind.Sync or TracingReturnKind.TaskOfT or TracingReturnKind.ValueTaskOfT;
        var parameters = string.Join(", ", method.Parameters.Select(p => $"{p.Type} {Escape(p.Name)}"));
        var arguments = string.Join(", ", method.Parameters.Select(p => Escape(p.Name)));
        source.AppendLine($"    public {(asynchronous ? "async " : "")}{method.ReturnType} {Escape(method.Name)}({parameters})");
        source.AppendLine("    {");
        source.AppendLine($"        using var activity = _activitySource.StartActivity(\"{contract.Name}.{method.Name}\", ActivityKind.Internal);");
        source.AppendLine($"        activity?.SetTag(\"code.function\", \"{method.Name}\");");
        source.AppendLine($"        activity?.SetTag(\"code.namespace\", \"{contract.FullName}\");");
        foreach (var parameter in method.Parameters.Where(p => p.IsTaggable))
            source.AppendLine($"        activity?.SetTag(\"{TagName(parameter.Name)}\", {Escape(parameter.Name)});");
        source.AppendLine("        try");
        source.AppendLine("        {");
        source.AppendLine($"            {(returnsValue ? "var result = " : "")}{(asynchronous ? "await " : "")}_inner.{Escape(method.Name)}({arguments});");
        source.AppendLine("            activity?.SetStatus(ActivityStatusCode.Ok);");
        if (returnsValue) source.AppendLine("            return result;");
        source.AppendLine("        }");
        source.AppendLine("        catch (global::System.Exception ex)");
        source.AppendLine("        {");
        source.AppendLine("            activity?.SetStatus(ActivityStatusCode.Error, ex.Message);");
        source.AppendLine("            activity?.AddException(ex);");
        source.AppendLine("            throw;");
        source.AppendLine("        }");
        source.AppendLine("    }");
    }

    private static string Escape(string name) => SyntaxFacts.GetKeywordKind(name) != SyntaxKind.None ? "@" + name : name;

    private static string TagName(string name)
    {
        var result = new StringBuilder();
        for (var i = 0; i < name.Length; i++)
        {
            if (char.IsUpper(name[i]) && i > 0) result.Append('_');
            result.Append(char.ToLowerInvariant(name[i]));
        }
        return result.ToString();
    }
}
